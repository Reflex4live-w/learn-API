// «REST — это архитектурный подход к построению API.
//  Я как фронтендер опираюсь на несколько ключевых принципов:

// Первый — единообразие интерфейса. Это значит, что все ресурсы 
// строятся по одному шаблону: используются существительные в URL 
// (например, /users), а действия определяются методами HTTP 
// (GET, POST, PUT, DELETE). Мне не нужно изучать разные форматы 
// для каждого эндпоинта.

// Второй — stateless, отсутствие состояния на сервере. 
// Сервер не запоминает меня между запросами, поэтому я
//  каждый раз передаю токен авторизации в заголовке Authorization. 
//  Это позволяет серверу масштабироваться без потери сессий.
//JWT token

// Третий — клиент-серверное разделение. Я отвечаю за интерфейс и 
// пользовательский опыт, сервер отвечает за данные и бизнес-логику. 
// Мы связаны только через API-контракт.

// Четвертый — кэшируемость. Некоторые ответы сервер может кэшировать 
// через заголовок Cache-Control, чтобы уменьшить нагрузку и ускорить 
// загрузку для пользователя.

// Пятый — слоистая система. Мне как клиенту не важно, как устроена
//  инфраструктура на сервере. Я просто хожу по одному адресу, а за 
//  ним может быть балансировщик или прокси-сервер».


