// Пункт 1. Единообразие интерфейса (Uniform Interface)
// Что это такое (своими словами)
// Это правило: "Все двери в здании должны открываться одинаково".

// Если ты уже знаешь, как получить список пользователей (GET /users), то ты автоматически знаешь, как получить список товаров (GET /products). Не нужно учить новое правило для каждого ресурса.

// Почему это важно
// Чтобы любой разработчик (даже новый в команде) мог сразу понять API, не читая тонну документации. Это про предсказуемость.

// Как это выглядит в реальном API
// Правильно (единообразно):

// text
// GET    /users          → список всех пользователей
// GET    /users/5        → одного пользователя с id=5
// POST   /users          → создать нового
// PUT    /users/5        → полностью обновить пользователя 5
// DELETE /users/5        → удалить пользователя 5
// Неправильно (бардак — так не делают):

// text
// GET    /getAllUsers    → список
// GET    /showUser?id=5  → одного
// POST   /createNewUser  → создать
// POST   /updateUser     → обновить (используют POST вместо PUT)
// GET    /deleteUser?id=5 → удаляют через GET (кошмар!)



